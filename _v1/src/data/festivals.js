// Fixed-BS-date civic holidays that recur identically every year. Used as
// a fallback for years outside the two verified gazette years above.
export const FIXED_ANNUAL = [
  {m:1,d:1,name:"Nepali New Year",tag:"holiday"},
  {m:1,d:18,name:"Labour Day",tag:"holiday"},
  {m:2,d:15,name:"Republic Day",tag:"holiday"},
  {m:6,d:3,name:"Constitution Day",tag:"holiday"},
  {m:10,d:16,name:"Martyrs' Day",tag:"holiday"},
  {m:11,d:7,name:"Democracy Day",tag:"holiday"},
];

export function festivalsFor(year, month, day) {
  const key = `${year}-${month}-${day}`;
  if (FESTIVALS[key]) return FESTIVALS[key];
  if (year < 2082 || year > 2083) {
    const hit = FIXED_ANNUAL.find((f) => f.m === month && f.d === day);
    if (hit) return [{ name: hit.name, tag: hit.tag }];
  }
  return [];
}
